// Token Radar model v2 ("radar-2"): rank pre-token protocols by implied launch value.
//
// The value is derived only from the sealed snapshot's own figures. For each
// category we take the MEDIAN market-cap-to-TVL ratio of the tokened protocols
// in that category (a category needs at least five tokened peers, otherwise
// the global median is used, so one-token categories cannot set the price).
// Then:
//
//   implied = round( tvl_usd x multiple x growth_factor x age_factor )
//
//   growth_factor = 1 + clamp(change_7d, -50, +200) / 100 x 0.5
//                   (change_7d unreported -> 1.0, shown as "not reported")
//   age_factor    = 1 + min(age_days, 1095) / 1095 x 0.25
//                   (listed_at missing -> 1.0)
//
// No protocol name is ever special-cased: the same function scores every row.
// The board holds the whole 40-protocol watchlist plus the 160 pre-token
// protocols below the watchlist floor with the largest TVL. Protocols whose
// token already trades are kept apart in a separate live view, never ranked.

/** One protocol entry: exactly the ten fields the sealed snapshot carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole sealed snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, stated in the dashboard so a reader can redo the math. */
export interface ModelConstants {
  min_peers: number;
  mult_floor: number;
  mult_cap: number;
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  age_weight: number;
  age_days: number;
}

export const MODEL: ModelConstants = {
  min_peers: 5,
  mult_floor: 0.02,
  mult_cap: 2.0,
  growth_weight: 0.5,
  growth_floor: -50,
  growth_cap: 200,
  age_weight: 0.25,
  age_days: 1095,
};

/** The model's version label: the dashboard names it. */
export const MODEL_VERSION = 'radar-2';

/** How many pre-token protocols below the watchlist floor the early radar carries, by TVL. */
export const EARLY_ROWS = 160;

/** How many live-token protocols the dashboard's live view carries, by market cap. */
